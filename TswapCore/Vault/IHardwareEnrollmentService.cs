namespace TswapCore.Vault;

/// <summary>
/// What a wrap/seal backend hands back from <see cref="IHardwareEnrollmentService.Enroll"/>:
/// the freshly generated 32-byte <c>KEK_slot</c> (held in memory only, never persisted) and
/// <paramref name="HwBlob"/>, the backend's own opaque blob from which it alone can recover
/// <c>KEK_slot</c> later. Deliberately not a <see cref="Config"/>: the backend returns its own
/// field and the caller decides where it is stored.
/// </summary>
public sealed record HardwareEnrollment(byte[] KekSlot, byte[] HwBlob);

/// <summary>
/// The enrollment counterpart of <see cref="IHardwareKeyService"/> (issue #151, option (b)):
/// "provision this machine's <c>KEK_slot</c> and return it, together with whatever this backend
/// needs to recover it later." A sibling interface rather than a method on
/// <see cref="IHardwareKeyService"/> so that seam stays a pure unlock seam and a backend can be
/// unlock-only.
///
/// <para>Implemented by the backends that <em>wrap</em> caller-generated bytes: the Secure
/// Enclave, Linux TPM and Windows TPM services, and the simulated test backend. Each generates
/// <c>KEK_slot</c> randomly inside <see cref="Enroll"/>. The YubiKey backend does not implement
/// it: a YubiKey cannot wrap bytes, it <em>derives</em> <c>KEK_slot</c> from an interactive
/// two-key challenge, so <c>InitCommand</c> keeps deriving it and passes it in. No console I/O
/// moves behind this interface. See <c>HARDWARE_BACKENDS.md</c> §Adding a backend.</para>
/// </summary>
public interface IHardwareEnrollmentService
{
    /// <summary>Which <see cref="Config.Backend"/> value this implementation enrolls for.</summary>
    HardwareBackend Backend { get; }

    /// <summary>True for the simulated test backend; false for real hardware.</summary>
    bool IsSimulated { get; }

    /// <summary>
    /// Generates a random 32-byte <c>KEK_slot</c>, wraps or seals it to this machine's hardware,
    /// and returns both. The blob is useless off this machine.
    /// </summary>
    HardwareEnrollment Enroll();
}
